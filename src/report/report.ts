/**
 * Human-readable audit trail generated from the machine records. Never hand-edit the output:
 * regenerate with `cc report`. Records (jsonl/json) are the source of truth.
 */
import fs from 'node:fs';
import path from 'node:path';
import { Episode } from '../core/episode';
import { readJson, readJsonl } from '../core/io';
import { paths } from '../core/paths';
import {
  AssetsFile,
  FactsFile,
  MetricSnapshot,
  Plan,
  PublishRecord,
  QaRecord,
  RenderRecord,
  ResearchFile,
  type MetricSnapshot as Metric,
} from '../core/schemas';

const opt = <T>(file: string, fn: () => T): T | undefined => (fs.existsSync(file) ? fn() : undefined);
const esc = (s: string) => s.replace(/\|/g, '\\|').replace(/\n/g, ' ');
const table = (head: string[], rows: string[][]) =>
  [
    `| ${head.join(' | ')} |`,
    `| ${head.map(() => '---').join(' | ')} |`,
    ...rows.map((r) => `| ${r.map(esc).join(' | ')} |`),
  ].join('\n');

export function episodeReport(ep: Episode): string {
  const p = ep.paths;
  const m = ep.manifest;
  const plan = opt(p.plan, () => readJson(p.plan, Plan));
  const research = opt(p.research, () => readJson(p.research, ResearchFile));
  const facts = opt(p.facts, () => readJson(p.facts, FactsFile))?.facts ?? [];
  const assets = opt(p.assets, () => readJson(p.assets, AssetsFile))?.assets ?? [];
  const render = opt(p.render, () => readJson(p.render, RenderRecord));
  const qa = opt(p.qa, () => readJson(p.qa, QaRecord));
  const publish = opt(p.publish, () => readJson(p.publish, PublishRecord));
  const metrics = readJsonl(p.metrics, MetricSnapshot);
  const out: string[] = [];

  out.push(
    `# ${plan?.title ?? m.id}`,
    '',
    '> Generated by `pnpm cc report`. Do not edit — the JSON/JSONL files in this folder are the source of truth.',
    '',
  );
  out.push(
    table(
      ['Field', 'Value'],
      [
        ['Episode', m.id],
        ['Series', m.series],
        ['Stage', `**${m.stage}**`],
        ['Created', m.createdAt],
        [
          'Location',
          m.location ? `${m.location.label} (${m.location.lat}°, ${m.location.lon}°, ${m.location.timeZone})` : '—',
        ],
        ['Window', m.window ? `${m.window.start} → ${m.window.end}` : '—'],
      ],
    ),
    '',
  );

  const decisions = ep.decisions();
  out.push('## Decisions', '');
  if (!decisions.length) out.push('_None recorded yet._', '');
  for (const d of decisions) {
    out.push(
      `### ${d.ts.slice(0, 16).replace('T', ' ')} · ${d.stage} · ${d.actor}`,
      '',
      `**${d.decision}**`,
      '',
      d.rationale,
      '',
    );
    if (d.alternatives.length) out.push('Alternatives considered:', ...d.alternatives.map((a) => `- ${a}`), '');
    if (d.inputs.length) out.push(`Inputs: ${d.inputs.map((i) => `\`${i}\``).join(', ')}`, '');
  }

  if (research) {
    out.push(
      '## Research — detected events',
      '',
      table(
        ['Score', 'Event', 'When (UTC)', 'Best view'],
        research.events.map((e) => [
          String(e.score),
          e.title,
          e.time.slice(0, 16),
          e.viewing ? `${e.viewing.bestLocal}, ${e.viewing.direction}, ${Math.round(e.viewing.altitude)}°` : '—',
        ]),
      ),
      '',
    );
  }

  if (plan) {
    out.push('## Script', '');
    for (const s of plan.scenes) {
      out.push(
        `**${s.id}** (\`${s.template}\`) — facts: ${s.factIds.map((f) => `\`${f}\``).join(', ') || '—'}`,
        '',
        ...s.narration.map((n) => `> ${n}`),
        '',
      );
    }
    out.push(
      '### Post copy',
      '',
      `**${plan.post.title}**`,
      '',
      plan.post.description,
      '',
      plan.post.hashtags.join(' '),
      '',
    );
  }

  const used = new Set(plan?.scenes.flatMap((s) => s.factIds) ?? []);
  if (facts.length) {
    out.push(
      '## Facts used',
      '',
      table(
        ['Fact', 'Statement', 'Source'],
        facts
          .filter((f) => used.has(f.id))
          .map((f) => [
            f.id,
            f.statement,
            f.source.type === 'url'
              ? `[${f.source.publisher ?? f.source.title}](${f.source.url})`
              : `computed (${f.source.method})`,
          ]),
      ),
      '',
    );
  }

  if (assets.length) {
    out.push(
      '## Assets',
      '',
      table(
        ['Asset', 'Source', 'Credit', 'License', 'AI'],
        assets.map((a) => [
          a.id,
          `[${a.source.title}](${a.source.pageUrl ?? a.source.url})`,
          a.source.credit,
          a.source.license,
          a.aiGenerated ? 'yes' : 'no',
        ]),
      ),
      '',
    );
  }

  if (render)
    out.push(
      '## Render',
      '',
      `${render.durationSec.toFixed(1)} s, ${render.width}×${render.height}@${render.fps}, sha256 \`${render.videoSha256.slice(0, 16)}…\`, rendered ${render.renderedAt} in ${Math.round(render.renderSeconds)} s.`,
      '',
    );

  if (qa) {
    out.push(
      '## QA',
      '',
      table(
        ['Check', 'OK', 'Detail'],
        qa.automated.map((c) => [c.name, c.ok ? '✅' : '❌', c.detail]),
      ),
      '',
    );
    if (qa.visualReview)
      out.push(
        `Visual review by **${qa.visualReview.actor}** (${qa.visualReview.at}): **${qa.visualReview.verdict}** — ${qa.visualReview.notes}`,
        '',
      );
  }

  if (m.approvals.length)
    out.push(
      '## Approvals',
      '',
      ...m.approvals.map(
        (a) =>
          `- ${a.at} — **${a.by}** (${a.actor}) approved video \`${a.videoSha256.slice(0, 16)}…\`${a.note ? `: ${a.note}` : ''}`,
      ),
      '',
    );

  if (publish?.attempts.length) {
    out.push('## Publishing', '');
    for (const a of publish.attempts) {
      out.push(
        `### ${a.at} · ${a.mode}${a.dryRun ? ' (dry run)' : ''}`,
        '',
        table(
          ['Platform', 'Status', 'Postiz id', 'Error'],
          a.targets.map((t) => [t.platform, t.status, t.postizPostId ?? '—', t.error ?? '']),
        ),
        '',
      );
    }
  }

  if (metrics.length)
    out.push(
      '## Metrics',
      '',
      table(
        ['At', 'Platform', 'Views', 'Likes', 'Avg view %', 'Source'],
        metrics.map((x) => [
          x.at.slice(0, 16),
          x.platform,
          String(x.views),
          String(x.likes ?? '—'),
          String(x.avgViewPct ?? '—'),
          x.source,
        ]),
      ),
      '',
    );

  out.push(
    '## Event log',
    '',
    table(
      ['Time (UTC)', 'Actor', 'Stage', 'Action', 'Git'],
      ep.logs().map((l) => [l.ts.slice(0, 19).replace('T', ' '), l.actor, l.stage, l.action, l.gitSha ?? '']),
    ),
    '',
  );
  return out.join('\n');
}

function latestViews(metrics: Metric[]): number {
  const byPlatform = new Map<string, Metric>();
  for (const x of metrics) {
    const prev = byPlatform.get(x.platform);
    if (!prev || prev.at < x.at) byPlatform.set(x.platform, x);
  }
  return [...byPlatform.values()].reduce((n, x) => n + x.views, 0);
}

export function ledger(): string {
  const rows = Episode.list(paths.episodes).map((id) => {
    const ep = Episode.load(id);
    const plan = opt(ep.paths.plan, () => readJson(ep.paths.plan, Plan));
    const pub = opt(ep.paths.publish, () => readJson(ep.paths.publish, PublishRecord));
    const live =
      pub?.attempts
        .filter((a) => !a.dryRun)
        .flatMap((a) => a.targets.filter((t) => t.status === 'submitted').map((t) => t.platform)) ?? [];
    const views = latestViews(readJsonl(ep.paths.metrics, MetricSnapshot));
    return [
      `[${id}](../episodes/${id}/README.md)`,
      ep.manifest.series,
      ep.stage,
      plan?.post.title ?? '—',
      [...new Set(live)].join(', ') || '—',
      views ? String(views) : '—',
    ];
  });
  return [
    '# Episode ledger',
    '',
    '> Generated by `pnpm cc report`. One row per episode; open an episode for its full trace.',
    '',
    table(['Episode', 'Series', 'Stage', 'Title', 'Published to', 'Views (latest)'], rows),
    '',
  ].join('\n');
}

export function writeReports(episodeIds?: string[]): string[] {
  const written: string[] = [];
  for (const id of episodeIds ?? Episode.list(paths.episodes)) {
    const ep = Episode.load(id);
    fs.writeFileSync(ep.paths.readme, episodeReport(ep));
    written.push(path.relative(paths.root, ep.paths.readme));
  }
  const ledgerFile = path.join(paths.docs, 'ledger.md');
  fs.mkdirSync(paths.docs, { recursive: true });
  fs.writeFileSync(ledgerFile, ledger());
  written.push(path.relative(paths.root, ledgerFile));
  return written;
}
