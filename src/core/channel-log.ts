/**
 * Channel-level decisions (strategy, series, formats, policy) — the counterpart of an episode's
 * decisions.jsonl. Rendered to docs/decisions/README.md by `cc report`.
 */
import path from 'node:path';
import { appendJsonl, nowIso, readJsonl } from './io';
import { paths } from './paths';
import { Decision } from './schemas';

export const channelDecisionsFile = (): string => path.join(paths.docs, 'decisions', 'decisions.jsonl');

export function recordChannelDecision(d: Omit<Decision, 'ts'>): Decision {
  const decision = Decision.parse({ ...d, ts: nowIso() });
  appendJsonl(channelDecisionsFile(), decision);
  return decision;
}

export function channelDecisions(): Decision[] {
  return readJsonl(channelDecisionsFile(), Decision);
}

export function channelDecisionsMarkdown(): string {
  const ds = channelDecisions();
  const out = [
    '# Channel decision log',
    '',
    '> Generated by `pnpm cc report` from `decisions.jsonl`. Append with `pnpm cc decision --channel …`.',
    '> Episode-level decisions live in each `episodes/<id>/decisions.jsonl`.',
    '',
  ];
  for (const d of [...ds].reverse()) {
    out.push(`## ${d.ts.slice(0, 10)} · ${d.stage} · ${d.actor}`, '', `**${d.decision}**`, '', d.rationale, '');
    if (d.alternatives.length) out.push('Alternatives considered:', ...d.alternatives.map((a) => `- ${a}`), '');
    if (d.inputs.length) out.push(`Inputs: ${d.inputs.map((i) => `\`${i}\``).join(', ')}`, '');
  }
  return out.join('\n');
}
