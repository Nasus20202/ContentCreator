/**
 * Regenerate docs/cli.md from the CLI's own --help output: `pnpm docs:cli`.
 * Lists the commands worth documenting; anything else is one `--help` away.
 */
import { execFileSync } from 'node:child_process';
import fs from 'node:fs';

const COMMANDS = [
  'episode new',
  'episode rename',
  'research sky',
  'fact add',
  'asset search',
  'asset add',
  'asset restore',
  'plan',
  'factcheck',
  'voice',
  'render',
  'qa',
  'approve',
  'publish episode',
  'publish reschedule',
  'publish unschedule',
  'publish channels',
  'decision',
  'metrics add',
  'report',
  'validate',
];

const help = (args: string[]) =>
  execFileSync('npx', ['tsx', 'src/cli/index.ts', ...args, '--help'], { encoding: 'utf8' }).trimEnd();
const block = (text: string) => ['```text', text, '```'].join('\n');

const parts = [
  '# CLI reference',
  '',
  '> Generated by `pnpm docs:cli` from `pnpm cc --help`. Run any command with `--help` for details.',
  '',
  block(help([])),
];
for (const c of COMMANDS) parts.push('', `## cc ${c}`, '', block(help(c.split(' '))));
fs.writeFileSync('docs/cli.md', parts.join('\n') + '\n');
console.log(`docs/cli.md: ${COMMANDS.length} commands`);
